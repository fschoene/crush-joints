    float Distortion::tubeDistort(float x, float tubeNormalized)
    {
        int idx = round(tubeNormalized * 100.0f);
        idx = juce::jlimit(0, 100, idx);
        float gain = disttube_coeffs[idx][0];  // 1.0 to ~5.0
        float a = disttube_coeffs[idx][1];
        float b = disttube_coeffs[idx][2];
        float c = disttube_coeffs[idx][3];
        float s = x * gain;
        
        if (s > 0.6f)
            return -a*s*s + b*s - c;
        else if (s < -0.6f)
            return a*s*s + b*s + c;
        else
            return s;
    }

    float Distortion::mechDistort(float y, float mechNormalized)
    {
        int idx = round(mechNormalized * 100.0f);
        idx = juce::jlimit(0, 100, idx);
        float gain = distmech_coeffs[idx][0];  // 1.0 to ~11.0
        float b = distmech_coeffs[idx][1];
        float c = distmech_coeffs[idx][2];
        float s = y * gain;
        
        if (s > 0.75f)
            return b*s - c;
        else if (s < -0.75f)
            return b*s + c;
        else
            return s;
    }
