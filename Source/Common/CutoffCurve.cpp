    float toHz(float normalised) noexcept
    {
        const float position = std::clamp(normalised, 0.0f, 1.0f) * static_cast<float>(kNumPoints - 1);
        const int index = std::min(static_cast<int>(position), kNumPoints - 2);
        const float fraction = position - static_cast<float>(index);

        return kTable[static_cast<size_t>(index)]
             + (kTable[static_cast<size_t>(index) + 1] - kTable[static_cast<size_t>(index)]) * fraction;
    }

    float toNormalised(float hz) noexcept
    {
        if (hz <= kMinHz)
            return 0.0f;

        if (hz >= kMaxHz)
            return 1.0f;

        // The table is non-decreasing; find the segment containing hz.
        const auto upper = std::upper_bound(kTable.begin(), kTable.end(), hz);
        const int index = std::clamp(static_cast<int>(upper - kTable.begin()) - 1, 0, kNumPoints - 2);

        const float low = kTable[static_cast<size_t>(index)];
        const float high = kTable[static_cast<size_t>(index) + 1];
        const float fraction = high > low ? (hz - low) / (high - low) : 0.0f;

        return (static_cast<float>(index) + fraction) / static_cast<float>(kNumPoints - 1);
    }
